export function measureTextWidth(text) {
  let width = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const glyph = FONT_5PX[ch] ?? FONT_5PX[ch.toUpperCase()] ?? FONT_5PX[' '];
    width += glyph[0].length;
    if (i < text.length - 1) width += 1;
  }
  return width;
}
